class AgentTest_get_portfolio_summary(unittest.TestCase):
    def test_get_portfolio_summary_1(self):
        tracker = StockPortfolioTracker(1000.0)
        tracker.portfolio = [{'name': 'AAPL', 'price': 200.0, 'quantity': 3},
                             {'name': 'MSFT', 'price': 80.5, 'quantity': 5}]
        total, summary = tracker.get_portfolio_summary()
        self.assertAlmostEqual(total, 2002.5)
        self.assertEqual(summary, [{'name': 'AAPL', 'value': 600.0},
                                   {'name': 'MSFT', 'value': 402.5}])

    def test_get_portfolio_summary_2(self):
        tracker = StockPortfolioTracker(500.0)
        tracker.portfolio = [{'name': 'MSFT', 'price': 80.5, 'quantity': 4},
                             {'name': 'AAPL', 'price': 200.0, 'quantity': 1}]
        total, summary = tracker.get_portfolio_summary()
        self.assertEqual(total, 1022.0)
        self.assertEqual(len(summary), 2)
        for entry in summary:
            self.assertEqual(set(entry.keys()), {'name', 'value'})
        self.assertEqual(summary, [{'name': 'MSFT', 'value': 322.0},
                                   {'name': 'AAPL', 'value': 200.0}])