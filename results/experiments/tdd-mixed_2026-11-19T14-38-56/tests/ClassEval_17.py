import unittest

from datetime import datetime, timedelta

class AgentTest_get_available_slots(unittest.TestCase):
    def test_get_available_slots_1(self):
        calendar = CalendarUtil()
        calendar.events = [
            {'date': datetime(2023, 1, 1, 0, 0), 'start_time': datetime(2023, 1, 1, 8, 0),
             'end_time': datetime(2023, 1, 1, 9, 0), 'description': 'Morning'},
            {'date': datetime(2023, 1, 1, 0, 0), 'start_time': datetime(2023, 1, 1, 12, 0),
             'end_time': datetime(2023, 1, 1, 13, 0), 'description': 'Lunch'},
        ]
        base = datetime(2023, 1, 1)
        busy_hours = {8, 12}
        expected = [(base + timedelta(hours=h), base + timedelta(hours=h + 1))
                    for h in range(24) if h not in busy_hours]
        self.assertEqual(calendar.get_available_slots(datetime(2023, 1, 1)), expected)

    def test_get_available_slots_2(self):
        calendar = CalendarUtil()
        calendar.events = [{'date': datetime(2023, 1, 1, 0, 0), 'start_time': datetime(2023, 1, 1, 0, 0),
                            'end_time': datetime(2023, 1, 2, 0, 0), 'description': 'All day'}]
        self.assertEqual(calendar.get_available_slots(datetime(2023, 1, 1)), [])

